/* ---------- помощники игр ---------- */
const cap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
/** последняя «играбельная» буква слова (мягкий/твёрдый знак пропускаем) */
const cityTail = (w: string): string => {
  const s = w.replace(/[ьъ]+$/, '').trim();
  return s ? s[s.length - 1].toLowerCase() : '';
};

