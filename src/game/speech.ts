function isExplicitCommand(t: string): boolean {
  return (
    /^(привет|здравств|хай|добр|салют|hello|hi|ку|йо)/.test(t) ||
    /(как дела|как ты|как поживаешь|как настроен|что нового|как себя чувствуешь)/.test(t) ||
    /(как тебя зовут|тво[её] имя|кто ты|расскажи о себе)/.test(t) ||
    /(что делал|чем занимался|как прош[её]л твой день)/.test(t) ||
    /(который час|сколько времени|какое число|какой день)/.test(t) ||
    /(какая погода|что за окном|на улице)/.test(t) ||
    /(что ты умеешь|что можешь|твои способности)/.test(t) ||
    /(что ты помнишь|что помнишь|твои воспоминания)/.test(t) ||
    /(спой|спо[её]шь|песенку|песню)/.test(t) ||
    /(расскажи факт|какой-нибудь факт|что-нибудь интересное|удиви меня)/.test(t) ||
    /сколько будет\s+\d/.test(t) ||
    /(шутк|анекдот|смешн|ха-ха|хаха|ахах)/.test(t) ||
    /(спасибо|благодар)/.test(t) ||
    /(пить|воды|вода)/.test(t) ||
    /(спать|сон|поздно)/.test(t) ||
    /(поиграем|поиграть|во что поиграть|мне скучно|в города|в ассоциации)/.test(t) ||
    /(сказку|расскажи историю|комплимент)/.test(t)
  );
}

function followUp(state: GameState): string {
  const dlg = state.dialog;
  if (!state.owner.name) {
    dlg.pendingQuestion = 'name';
    return 'А как тебя зовут? Мне очень хочется знать.';
  }
  if (!state.owner.favorites.length && Math.random() < 0.6) {
    dlg.pendingQuestion = 'favorite';
    return 'А что тебе больше всего нравится делать? Расскажи!';
  }
  const opts: Array<[GameState['dialog']['pendingQuestion'], string]> = [
    ['mood', 'А как у тебя сегодня настроение?'],
    ['day', 'Как прошёл твой день? Расскажешь?'],
    ['memory', 'А какое у тебя самое тёплое воспоминание?'],
    ['good', 'Расскажи мне что-нибудь хорошее про сегодня?'],
  ];
  const [key, q] = opts[Math.floor(Math.random() * opts.length)];
  dlg.pendingQuestion = key;
  return q;
}

export function chatBrain(
  text: string,
  state: GameState,
  fact?: { title: string; text: string } | null,
): BrainResult {
  const t = text.toLowerCase().trim();
  const pet = state.pet!;
  const petName = pet.name;
  const ownerName = state.owner.name ? `, ${state.owner.name}` : '';
  const st = pet.stats;
  const dlg = state.dialog;

  /* ============ активная игра в чате важнее всего остального ============ */
  if (dlg.game) return gameMove(t, text, state);

  /* ============ 0) Контекст: хозяин отвечает на вопрос питомца ============
     Пропускаем, если это явная команда («расскажи факт», «как дела» и т.д.) —
     она обработается движком намерений, а pendingQuestion сохранится,
     чтобы хозяин мог ответить на вопрос позже. */
  if (dlg.pendingQuestion && !isExplicitCommand(t)) {
    const q = dlg.pendingQuestion;
    dlg.pendingQuestion = null;
    if (q === 'name') {
      const nm = t.replace(/^(меня зовут|мо[её] имя|звать меня)\s*/i, '').trim().split(/[\s,.!?]+/)[0];
      if (nm && nm.length >= 2 && nm.length <= 20) {
        const name = nm.charAt(0).toUpperCase() + nm.slice(1);
        return {
          lines: [`${name}! Какое красивое имя. Теперь я буду звать тебя только так.`, `Приятно познакомиться, ${name}! А я — ${petName}.`],
          save: { kind: 'факт', text: `Хозяина зовут ${name}` }, ownerName: name, moodDelta: 3,
        };
      }
    } else if (q === 'mood') {
      const good = /(хорош|отличн|прекрасн|супер|классн|здоров|нормальн|неплох|весел|радост)/.test(t);
      const bad = /(плохо|ужасн|грустн|устал|тяжел|печаль|одиноко|болит)/.test(t);
      state.owner.moods.push(good ? 85 : bad ? 30 : 60);
      if (good) return { lines: ['Вот и чудесно! Когда у тебя хорошо — у меня хвост сам собой виляет.', 'Так держать! Может, сделаем что-нибудь приятное вместе?'], moodDelta: 3 };
      if (bad) return { lines: ['Ой… иди ко мне. Расскажи, что случилось?', 'Я рядом. Давай посидим тихо-тихо, а потом станет легче. Обещаю.'], save: { kind: 'эмоция', text: 'Хозяину было грустно — обнял крепко' }, moodDelta: 4 };
      return { lines: ['Понятненько. Главное — береги себя, ладно?', 'Спасибо, что рассказал. Мне правда важно знать.'], moodDelta: 2 };
    } else if (q === 'day') {
      const nice = /(хорош|отличн|интересн|весел|продуктивн)/.test(t);
      return {
        lines: ['Спасибо, что поделился! Записал в наш общий дневник.', `Звучит как ${nice ? 'чудесный' : 'непростой'} день. Я горжусь тобой в любом случае.`],
        save: { kind: 'момент', text: `Хозяин рассказал про день: ${text.slice(0, 70)}` }, moodDelta: 3,
      };
    } else if (q === 'favorite') {
      const fav = text.replace(/[.!]/g, '').trim().slice(0, 40);
      if (fav) {
        if (!state.owner.favorites.includes(fav)) state.owner.favorites.push(fav);
        return { lines: [`«${fav}»! Теперь это и моё любимое тоже.`, 'Запомнил навсегда. Будем заниматься этим вместе!'], save: { kind: 'факт', text: `Любимое: ${fav}` }, favorite: fav, moodDelta: 2 };
      }
    } else if (q === 'memory') {
      const mem = text.replace(/[.!]/g, '').trim().slice(0, 80);
      if (mem) {
        return {
          lines: ['Какое тёплое воспоминание… Спасибо, что поделился. Я буду его беречь.', 'Записал в самое надёжное место. Такие моменты — самое ценное.'],
          save: { kind: 'момент', text: `Тёплое воспоминание хозяина: ${mem}` }, moodDelta: 3,
        };
      }
    } else if (q === 'good') {
      const good = text.replace(/[.!]/g, '').trim().slice(0, 80);
      if (good) {
        return {
          lines: ['Вот это здорово! Сразу стало светлее.', 'Запомнил! Сегодня в мире стало на одно хорошее событие больше.'],
          save: { kind: 'момент', text: `Хорошее за сегодня: ${good}` }, moodDelta: 3,
        };
      }
    }
    /* если ответ не распознан — продолжаем обычный разбор ниже */
  }

  /* ============ свежее знание из Википедии (RAG без большой модели) ============
     Движок уже сходил в сеть по вопросу хозяина; питомец пересказывает
     найденное своими словами и сохраняет в память. */
  if (fact) {
    const body = fact.text.length > 220 ? fact.text.slice(0, 220).trim() + '…' : fact.text;
    return {
      lines: [
        `О! Я только что прочитал: ${body}`,
        R([
          'Правда, здорово? Спроси меня ещё о чём-нибудь — я люблю узнавать новое.',
          'Записал в блокнот открытий! Теперь я чуть-чуть энциклопедия.',
          'Вот это да! Расскажу потом во сне всем светлячкам.',
        ]),
      ],
      save: { kind: 'факт', text: `${fact.title}: ${fact.text.slice(0, 100)}` },
      moodDelta: 3,
    };
  }

  let m = t.match(/(?:меня зовут|мо[её] имя|звать меня)\s+([a-zа-яё]+(?:-[a-zа-яё]+)?)/i);
  if (m) {
    const name = m[1].charAt(0).toUpperCase() + m[1].slice(1);
    return {
      lines: [`${name}! Какое красивое имя. Я буду помнить его всегда-всегда.`, `Теперь мы официально знакомы. Я — ${petName}, а ты — ${name}!`],
      save: { kind: 'факт', text: `Хозяина зовут ${name}` }, ownerName: name, moodDelta: 3,
    };
  }
  if (/(как меня зовут|помнишь мо[её] имя|мо[её] имя)/.test(t)) {
    return state.owner.name
      ? { lines: [`Конечно помню! Тебя зовут ${state.owner.name}. Это моё самое надёжное воспоминание.`] }
      : { lines: ['Хм… ты ещё не говорил. Расскажешь? Напиши: «меня зовут …» — и я запомню навсегда.'] };
  }
  m = t.match(/(?:я люблю|мне нравится|обожаю)\s+(.+)/i);
  if (m && m[1].length < 40) {
    const fav = m[1].replace(/[.!]/g, '').trim();
    return {
      lines: [`«${fav}» — записал в любимое! Будем заниматься этим вместе.`, `Ого, ${fav}! Расскажешь потом подробнее? Мне правда интересно.`],
      save: { kind: 'факт', text: `Любимое: ${fav}` }, favorite: fav, moodDelta: 2,
    };
  }
  m = t.match(/запомни[:\s]+(.+)/i);
  if (m) {
    return { lines: ['Запомнил! Спрятал в самый надёжный кармашек памяти.', `«${m[1]}» — теперь это часть моей истории о тебе.`], save: { kind: 'факт', text: m[1] } };
  }
  m = t.match(/(?:обещаю|постараюсь|попробую)\s+(.+)/i);
  if (m) {
    return {
      lines: ['Я запомню это обещание. Не чтобы проверять — а чтобы поддержать.', 'Договорились. Я буду рядом, когда будешь это делать.'],
      save: { kind: 'обещание', text: m[1] }, moodDelta: 2,
    };
  }
  if (/(груст|плохо|устал|устала|тревог|печал|тяжело|одиноко|плакать|больно)/.test(t)) {
    state.owner.moods.push(30);
    return {
      lines: [
        'Иди ко мне. Я хоть и маленький, но вмещаю много тепла.',
        'Давай подышим вместе? Вдох на четыре счёта… выдох на шесть. Я рядом.',
        state.owner.favorites.length ? `Помню, тебе нравится ${state.owner.favorites[0]}. Может, чуть-чуть отвлечёмся на это?` : 'Расскажешь, что случилось? Я умею слушать ушами и всем сердцем.',
      ].slice(0, 2),
      save: { kind: 'эмоция', text: 'Хозяину было грустно — обнял крепко-крепко' }, moodDelta: 4,
    };
  }
  if (/(рад|счаст|отлично|ура|класс|здорово|кайф|успех|получилось)/.test(t)) {
    state.owner.moods.push(90);
    return {
      lines: ['УРА! У меня сейчас уши встанут торчком от радости!', 'Это надо отпраздновать! Я уже танцую. Видишь? Видишь?!'],
      save: { kind: 'эмоция', text: 'Разделили радость — день стал искристым' }, moodDelta: 5,
    };
  }

  /* ---------- давай поиграем / мне скучно: игры прямо в чате ---------- */
  if (/(поиграем|поиграть со мной|во что поиграть|мне скучно|скукота|давай повеселимся)/.test(t)) {
    if (/(в города|города)/.test(t)) return startCities(state);
    if (/(в ассоциации|ассоциации)/.test(t)) return startAssoc(state);
    return {
      lines: [
        'Ура, играем! У нас есть «Города» — ты называешь город, я продолжаю на последнюю букву. И «Ассоциации» — я слово, ты первое, что пришло в голову.',
        'Напиши «давай поиграем в города» или «в ассоциации» — и поехали!',
      ],
      moodDelta: 2,
    };
  }
  if (/(в города|сыграем в города|поиграем в города)/.test(t) && !dlg.game) return startCities(state);
  if (/(в ассоциации|сыграем в ассоциации|поиграем в ассоциации)/.test(t) && !dlg.game) return startAssoc(state);

  /* ---------- расскажи сказку / историю ---------- */
  if (/(сказку|сказка|расскажи историю|историю на ночь|расскажи что-нибудь доброе)/.test(t)) {
    return { lines: tellTale(state), moodDelta: 2 };
  }

  /* ---------- комплименты питомцу ---------- */
  if (/(ты (милый|умный|умная|классный|лучший|лучшая|чудесный|умненький|добрый)|люблю тебя|ты молодец|горжусь тобой|ты супер)/.test(t)) {
    return {
      lines: [R([
        'Ой… я сейчас покраснею. Видно? Я покра-а-аснел!',
        'У меня хвост сам завилял. Спасибо! Ты тоже самый лучший!',
        'Когда ты так говоришь, я свечусь ярче лампочки. Честно.',
      ])],
      save: { kind: 'эмоция', text: 'Хозяин похвалил — питомец сиял до вечера' }, moodDelta: 5,
    };
  }

  /* ---------- прощание ---------- */
  if (/^(пока|до завтра|спокойной ночи|доброй ночи|до встречи|бай)/.test(t)) {
    return {
      lines: [R([
        'Пока-пока! Я буду сторожить дом и считать звёзды.',
        'До встречи! Я приготовлю для тебя сон. Самый тёплый.',
        'До скорого! Мы с лампой будем ждать. Лампа уже скучает.',
      ])],
      moodDelta: 2,
    };
  }

  /* ---------- совет ---------- */
  if (/(что мне делать|посоветуй|что делать|не знаю, что|трудно решить|как мне быть)/.test(t)) {
    return {
      lines: [
        R([
          'Когда я не знаю, что делать — я делаю что-нибудь маленькое, но доброе. Всегда помогает.',
          'Давай подумаем вместе. Чего тебе сейчас хочется больше всего?',
          'Сделай глубокий вдох… Ответы любят приходить после какао.',
        ]),
        followUp(state),
      ],
      moodDelta: 2,
    };
  }

  /* ---------- кто я / как меня зовут (питомец рассказывает о себе) ---------- */
  if (/(как тебя зовут|тво[её] имя|кто ты|расскажи о себе)/.test(t)) {
    const sp = SPECIES.find(x => x.key === pet.dna.species);
    return {
      lines: [
        `Меня зовут ${petName}! Я ${sp?.label ?? 'маленькое чудо'}${sp ? ` — ${sp.desc.toLowerCase()}` : ''}.`,
        `А ещё я ${abilityFlavor(pet.dna.abilityId)}. И очень-очень рад, что ты со мной.`,
      ],
      moodDelta: 2,
    };
  }

  /* ---------- приветствие (по времени суток + встречный вопрос) ---------- */
  if (/^(привет|здравств|хай|добр|салют|hello|hi|ку|йо)/.test(t)) {
    const hour = new Date().getHours();
    const bank = hour < 5 ? GREETINGS.night : hour < 11 ? GREETINGS.morning : hour < 17 ? GREETINGS.day : hour < 22 ? GREETINGS.evening : GREETINGS.night;
    return { lines: [R(bank).replace('{owner}', ownerName), followUp(state)], moodDelta: 2 };
  }

  /* ---------- как дела / как настроение ---------- */
  if (/(как дела|как ты|как поживаешь|как настроен|что нового|как себя чувствуешь)/.test(t)) {
    const moodWord = st.mood > 70 ? 'искристо' : st.mood > 45 ? 'уютно' : 'немного туманно';
    const hunger = st.hunger < 35 ? ' И немножко хочется лунного печенья.' : '';
    const energy = st.energy < 30 ? ' Только глазки уже слипаются…' : '';
    const learned = pet.wordsLearned.length > 0
      ? `А ещё я выучил слово «${pet.wordsLearned[pet.wordsLearned.length - 1]}»!`
      : 'А ещё я учусь мечтать правильнее.';
    return {
      lines: [`У меня всё ${moodWord}!${hunger}${energy}`, learned, followUp(state)],
      moodDelta: 2,
    };
  }

  /* ---------- что ты сегодня делал ---------- */
  if (/(что делал|чем занимался|что ты делал|как прош[её]л твой день)/.test(t)) {
    const bits: string[] = [];
    const feed = state.counters.feed ?? 0;
    if (feed > 0) bits.push(`меня кормили ${feed} раз(а)`);
    if (state.counters.play) bits.push('мы играли');
    if (state.counters.walk) bits.push('мы гуляли');
    const dream = state.dreams[0];
    if (dream) bits.push(`видел сон про ${dream.text.replace(/^Мне снился /, '').split(',')[0]}`);
    const did = bits.length ? bits.join(', ') : 'пересчитывал пылинки и сторожил окно';
    return {
      lines: [
        `Сегодня ${did}.`,
        pet.wordsLearned.length ? `И да — я выучил слово «${pet.wordsLearned[pet.wordsLearned.length - 1]}». Горжусь собой.` : 'И немножко помечтал. Это тоже дело, между прочим.',
      ],
      moodDelta: 2,
    };
  }

  /* ---------- который час / какое число ---------- */
  if (/(который час|сколько времени|какое число|какой день)/.test(t)) {
    const now = new Date();
    return { lines: [`Сейчас ${now.getHours()}:${String(now.getMinutes()).padStart(2, '0')}, ${now.toLocaleDateString('ru-RU', { day: 'numeric', month: 'long' })}. Время летит, когда мы вместе!`] };
  }

  /* ---------- какая погода ---------- */
  if (/(какая погода|что за окном|на улице)/.test(t)) {
    const wr = state.weatherReal;
    if (wr) return { lines: [`За окном ${wr.label.toLowerCase()}. Я проверил — высунул нос и быстро спрятал.`, wr.kind === 'rain' || wr.kind === 'snow' ? 'Так что сегодня идеальный день, чтобы побыть в тепле со мной.' : 'Пойдём погуляем?'] };
    return { lines: ['Я выглянул в окно — там небо. Красивое! Но точнее не скажу: я же маленький. Расскажи, какая у тебя погода?'] };
  }

  /* ---------- что ты умеешь ---------- */
  if (/(что ты умеешь|что можешь|твои способности)/.test(t)) {
    return { lines: [
      'Я умею многое! Играть в «города» и «ассоциации» прямо здесь, рассказывать сказки, искать в энциклопедии факты о чём угодно, помнить всё, что ты мне расскажешь.',
      'А ещё я расту: чем больше мы занимаемся и общаемся, тем умнее я становлюсь. Спроси меня, например: «кто такой Пушкин?»',
    ] };
  }

  /* ---------- что ты помнишь ---------- */
  if (/(что ты помнишь|что помнишь|твои воспоминания)/.test(t)) {
    if (!state.memories.length) return { lines: ['Пока у меня мало воспоминаний — мы ведь недавно знакомы. Но я всё записываю!'] };
    const mem = state.memories.slice(0, 3).map(x => x.text.toLowerCase());
    return { lines: [`Я помню многое! Например: ${mem.join('; ')}.`, 'И это только начало. Я всё-всё записываю.'] };
  }

  /* ---------- спой ---------- */
  if (/(спой|спо[её]шь|песенку|песню)/.test(t)) {
    return { lines: ['♪ Ла-ла-ла, звёзды-светлячки, ♪ ♪ спать легли в свои сундучки… ♪', 'Это моя колыбельная! Я сочинил её сам. Ну… почти сам.'] };
  }

  /* ---------- расскажи факт / что-нибудь интересное (локальный запас) ---------- */
  if (/(расскажи факт|какой-нибудь факт|что-нибудь интересное|расскажи что-нибудь|удиви меня)/.test(t)) {
    const f = FALLBACK_FACTS[Math.floor(Math.random() * FALLBACK_FACTS.length)];
    return {
      lines: [`О! Я недавно узнал: ${f.title.toLowerCase()}. ${f.text}`, 'Правда, здорово? Я теперь самый умный малыш в округе!'],
      save: { kind: 'факт', text: `${f.title}: ${f.text.slice(0, 80)}` }, moodDelta: 2,
    };
  }

  /* ---------- простая математика ---------- */
  const calc = t.match(/сколько будет\s+(\d+)\s*([+\-*/xх×])\s*(\d+)/);
  if (calc) {
    const a = parseInt(calc[1], 10), b = parseInt(calc[3], 10);
    const op = calc[2].replace(/[xх×]/, '*');
    const val = op === '+' ? a + b : op === '-' ? a - b : op === '*' ? a * b : (b !== 0 ? Math.round((a / b) * 100) / 100 : 'нельзя делить на ноль!');
    return { lines: [`${a} ${op === '*' ? '×' : op} ${b} будет ${val}!`, 'Я считал на пальцах. На всех сразу. Получилось быстро!'] };
  }
  if (/(шутк|анекдот|смешн|ха-ха|хаха|ахах)/.test(t)) {
    return {
      lines: [R(JOKES), 'Хи-хи! У меня от смеха искры из ушей!'],
      save: { kind: 'шутка', text: 'Смеялись вместе над шутками' }, moodDelta: 4,
    };
  }
  if (/(спасибо|благодар)/.test(t)) {
    return { lines: [R(['Всегда пожалуйста! Это моя любимая работа.', 'Обнимашка в ответ. Бесплатно и навсегда.'])] };
  }
  if (/(пить|воды|вода)/.test(t)) return { lines: ['Вода — это жидкие звёзды. Пей! Я прослежу.'] };
  if (/(спать|сон|поздно)/.test(t)) return { lines: ['Спокойной ночи! Я посторожу твои сны. Если что — разбужу нежно.'] };

  /* ---------- fallback: любопытство + воспоминание или встречный вопрос ---------- */
  const recall: string[] = [];
  if (state.memories.length > 2 && Math.random() < 0.3) {
    const mem = R(state.memories);
    recall.push(`Кстати, я помню: ${mem.text.toLowerCase()}. Я всё помню.`);
  } else if (state.dreams.length && Math.random() < 0.25) {
    recall.push(`А знаешь, мне недавно снилось: ${state.dreams[0].text.replace(/^Мне снилось? /, '').toLowerCase()}`);
  }
  const lead = R([
    'Хм-м… как интересно! Расскажи ещё — я записываю каждое слово в невидимый блокнотик.',
    'Я пока маленький и многого не знаю, но я ОЧЕНЬ стараюсь понять.',
    'Запишу это в коллекцию твоих слов. У меня уже целая полка!',
    `Мне нравится, как ты рассказываешь${ownerName}. Продолжай, а я буду кивать умно.`,
  ]);
  /* чередуем: то питомец делится, то спрашивает — разговор живёт. */
  const tail = recall.length ? recall[0] : followUp(state);
  return { lines: [lead, tail], moodDelta: 1 };
}

export function proactiveLine(state: GameState): string {
  const p = state.pet!;
  const ownerName = state.owner.name ? `, ${state.owner.name}` : '';
  if (p.stats.hunger < 35) return R(HUNGRY_LINES);
  if (p.stats.energy < 30) return R(TIRED_LINES);
  if (p.bond > 70 && Math.random() < 0.4) return R(THANKS_LINES).replace('{owner}', ownerName);
  if (p.trust < 45) return R(LONELY_LINES);
  if (state.memories.length > 3 && Math.random() < 0.3) {
    const mem = state.memories[Math.floor(Math.random() * state.memories.length)];
    return `Я тут вспомнил: ${mem.text.toLowerCase()}. Хороший был момент.`;
  }
  if (state.quests.some(q => !q.claimed && q.progress >= q.target)) return 'Кажется, у нас есть выполненное задание! Загляни в ритуалы.';
  if (Math.random() < 0.35) return R(QUESTIONS_FOR_OWNER);
  return R(IDLE_THOUGHTS);
}

export function welcomeLine(awayMs: number, trust: number, petName: string): string {
  const h = awayMs / 3600000;
  if (h < 2) return 'Ты вернулся так быстро! Я даже соскучиться не успел. Почти.';
  if (h < 12) return `Я ждал! Честно. Ну, ждал и немного ${trust > 60 ? 'мечтал' : 'грустил'}.`;
  if (h < 48) return `${petName} тут без тебя вёл дневник. Хочешь, покажу?`;
  if (trust < 50) return 'Ты так долго отсутствовал… Я уже начал разговаривать с лампой. Но я рад. Правда.';
  return 'Я знал, что ты вернёшься. Я держал для тебя тёплое место.';
}
