export function makeDiaryText(ctx: { ownerName: string; fedTimes: number; playedTimes: number; avgMood: number; weather: string }): string {
  const parts: string[] = [];
  if (ctx.fedTimes > 0) parts.push(`Сегодня меня кормили ${ctx.fedTimes} раз(а) — ${ctx.fedTimes > 1 ? 'я почти круглый' : 'было вкусно'}.`);
  if (ctx.playedTimes > 0) parts.push('Мы играли, и я чуть не выиграл у самого себя.');
  if (ctx.avgMood >= 70) parts.push('Настроение сегодня искрилось, как лимонад.');
  else if (ctx.avgMood < 40) parts.push('День был немного серым, но я нашёл в нём одну тёплую крошку.');
  const ownerPhrase = ctx.ownerName ? `кажется, ${ctx.avgMood >= 60 ? 'улыбался' : 'немного устал'}` : 'заходил по делам';
  parts.push(R(DIARY_OBSERVATIONS).replace('{ownerPhrase}', ownerPhrase).replace('{weather}', ctx.weather));
  return parts.slice(0, 3).join(' ');
}

