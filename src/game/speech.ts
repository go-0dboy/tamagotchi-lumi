function stopGame(state: GameState, g: NonNullable<GameState['dialog']['game']>): BrainResult {
  state.dialog.game = null;
  const what = g.type === 'cities' ? 'городов' : 'слов';
  return {
    lines: [
      `Ладно, остановимся! Мы прошли ${g.round} ${what} — это уже целое путешествие.`,
      g.round >= 5 ? 'Было здорово! Давай как-нибудь ещё?' : 'Если захочешь — просто напиши «давай поиграем».',
    ],
    moodDelta: 2,
  };
}

function gameMove(t: string, raw: string, state: GameState): BrainResult {
  const g = state.dialog.game!;
  if (/(стоп|хватит|сдаюсь|пасс|закончим|заканчивай|надоело|выйти из игры)/.test(t)) return stopGame(state, g);

  if (g.type === 'cities') {
    const word = raw.replace(/[.!?]+$/g, '').trim();
    if (word.length < 2 || word.split(/\s+/).length > 3) {
      return { lines: ['Хм, это не очень похоже на город 🙂 Назови город или скажи «хватит».'] };
    }
    const wl = word.toLowerCase();
    const need = cityTail(g.lastWord);
    if (need && !wl.startsWith(need)) {
      return { lines: [
        `Хи-хи, «${cap(g.lastWord)}» заканчивается на «${need.toUpperCase()}»! Мне нужен город на эту букву.`,
        'Подсказка: можно и не очень известный город. Или скажи «хватит».',
      ] };
    }
    if (g.used.includes(wl)) return { lines: ['Этот уже был! Придумай новый — я в тебя верю.'] };
    g.used.push(wl); g.round++;

    const nextNeed = cityTail(wl);
    const candidates = CITIES.filter(c => !g.used.includes(c.toLowerCase()) && c.toLowerCase().startsWith(nextNeed));
    if (!candidates.length) {
      state.dialog.game = null;
      return {
        lines: [
          `«${cap(wl)}»… Ой. Я не знаю города на «${nextNeed.toUpperCase()}»! Ты выиграл!`,
          `Мы прошли ${g.round} городов. Запишу в дневник: сегодня меня обыграли в «города». С почётом!`,
        ],
        save: { kind: 'момент', text: `Играли в «города» — ${g.round} городов, хозяин победил` },
        moodDelta: 5,
      };
    }
    const mine = R(candidates);
    g.used.push(mine.toLowerCase());
    g.lastWord = mine;
    const cheer = g.round >= 5 ? ' Ого, мы разошлись!' : '';
    return { lines: [`${cap(wl)} — принял!${cheer} Тогда… ${mine}! Твоя буква — «${cityTail(mine).toUpperCase()}».`] };
  }

  /* ассоциации */
  const word = raw.replace(/[.!?]+$/g, '').trim().split(/\s+/)[0]?.toLowerCase() ?? '';
  if (word.length < 2) return { lines: ['Скажи словечко — любое! Первое, что пришло в голову.'] };
  if (g.used.includes(word)) return { lines: ['Такое уже было! Придумай другое — даже самое странное.'] };
  g.used.push(word); g.round++;
  const related = (ASSOC[word] ?? []).filter(x => !g.used.includes(x));
  const pool = related.length ? related : ASSOC_POOL.filter(x => !g.used.includes(x));
  const mine = R(pool.length ? pool : ASSOC_POOL);

  if (g.round >= 6) {
    state.dialog.game = null;
    return {
      lines: [
        `А у меня — «${mine}»!`,
        `Это уже ${g.round} ассоциаций — целая цепочка! У тебя очень тёплые слова, я их запомнил.`,
      ],
      save: { kind: 'момент', text: `Играли в «ассоциации» (${g.round} слов)` },
      moodDelta: 4,
    };
  }
  return { lines: [`«${cap(word)}»… а у меня — «${mine}»! Что у тебя всплывает на «${mine}»?`] };
}

