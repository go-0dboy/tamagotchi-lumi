/* Лёгкий пересказ «своими словами»: берём первые 1–2 предложения статьи,
   убираем скобки и сложные обороты, чтобы звучало как рассказ питомца. */
function paraphrase(extract: string): string {
  const clean = extract.replace(/\([^)]*\)/g, '').replace(/\s+/g, ' ').trim();
  const sentences = clean.split(/(?<=[.!?])\s+/).filter(s => s.length > 12);
  let core = sentences.slice(0, 2).join(' ');
  if (core.length > 220) core = core.slice(0, 217).replace(/\s+\S*$/, '') + '…';
  if (!core) core = clean.slice(0, 200);
  return core.charAt(0).toUpperCase() + core.slice(1);
}

